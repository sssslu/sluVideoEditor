import { contextBridge, ipcRenderer, webUtils } from 'electron';
import type { StudioAPI, JobEvent } from '../shared/types';
const api:StudioAPI={
  importColorLut:()=>ipcRenderer.invoke('color:import-lut'),
  importMedia:(paths)=>ipcRenderer.invoke('media:import',paths),
  getPathForFile:(file)=>webUtils.getPathForFile(file),
  mediaUrl:(path)=>`slu-media://file/${encodeURIComponent(path)}`,
  openProject:()=>ipcRenderer.invoke('project:open'),
  saveProject:(project,path,saveAs)=>ipcRenderer.invoke('project:save',project,path,saveAs),
  collectProject:project=>ipcRenderer.invoke('project:collect',project),
  autosave:(project)=>ipcRenderer.invoke('project:autosave',project),
  recoverProject:()=>ipcRenderer.invoke('project:recover'),
  listRecoveries:()=>ipcRenderer.invoke('project:recoveries'),
  loadRecovery:(id)=>ipcRenderer.invoke('project:load-recovery',id),
  exportProject:(project,settings)=>ipcRenderer.invoke('project:export',project,settings),
  cancelJob:(id)=>ipcRenderer.invoke('job:cancel',id),
  generateProxy:(media)=>ipcRenderer.invoke('media:proxy',media),
  stabilizeMedia:(media,options)=>ipcRenderer.invoke('media:stabilize',media,options),
  freezeFrame:(media,time)=>ipcRenderer.invoke('media:freeze',media,time),
  reverseMedia:(media,options)=>ipcRenderer.invoke('media:reverse',media,options),
  removePersonBackground:(media,options)=>ipcRenderer.invoke('media:cutout',media,options),
  enhancementInfo:()=>ipcRenderer.invoke('enhancement:info'),
  installEnhancementEngine:()=>ipcRenderer.invoke('enhancement:install'),
  enhanceMedia:(media,options)=>ipcRenderer.invoke('media:enhance',media,options),
  discardEnhancementPreview:mediaId=>ipcRenderer.invoke('enhancement:discard-preview',mediaId),
  trackMedia:(media,options)=>ipcRenderer.invoke('media:track',media,options),
  trackingStill:(id,media,time,maxDimension)=>ipcRenderer.invoke('tracking:still',id,media,time,maxDimension),
  cancelTrackingStill:id=>ipcRenderer.invoke('tracking:cancel-still',id),
  readTrackingPath:(path,time,limit)=>ipcRenderer.invoke('tracking:read',path,time,limit),
  reconnectTracking:(project,id)=>ipcRenderer.invoke('tracking:reconnect',project,id),
  analyzeVideoRange:(media)=>ipcRenderer.invoke('media:video-range',media),
  transcribe:(media,language,options)=>ipcRenderer.invoke('media:transcribe',media,language,options),
  installModel:(model)=>ipcRenderer.invoke('model:install',model),
  installSpeechEngine:()=>ipcRenderer.invoke('speech:install'),
  getSystemInfo:()=>ipcRenderer.invoke('system:info'),
  importSubtitles:()=>ipcRenderer.invoke('subtitles:import'),
  exportSubtitles:(cues)=>ipcRenderer.invoke('subtitles:export',cues),
  showInFolder:(path)=>ipcRenderer.invoke('system:reveal',path),
  openHelp:()=>ipcRenderer.invoke('system:help'),
  onJob:(callback)=>{const listener=(_e:Electron.IpcRendererEvent,data:JobEvent)=>callback(data);ipcRenderer.on('job:progress',listener);return()=>ipcRenderer.removeListener('job:progress',listener);},
  onProjectWarning:(callback)=>{const listener=(_e:Electron.IpcRendererEvent,message:string)=>callback(message);ipcRenderer.on('project:warning',listener);return()=>ipcRenderer.removeListener('project:warning',listener);},
  onMediaUpdated:(callback)=>{const listener=(_e:Electron.IpcRendererEvent,data:import('../shared/types').MediaAsset)=>callback(data);ipcRenderer.on('media:updated',listener);return()=>ipcRenderer.removeListener('media:updated',listener);},
  onPreviewStatus:(callback)=>{const listener=(_e:Electron.IpcRendererEvent,data:import('../shared/types').PreviewStatusEvent)=>callback(data);ipcRenderer.on('media:preview-status',listener);return()=>ipcRenderer.removeListener('media:preview-status',listener);}
};
contextBridge.exposeInMainWorld('studio',api);
